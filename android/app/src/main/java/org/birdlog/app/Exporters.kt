package org.birdlog.app

import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter
import kotlin.math.*

object Exporters {
    private fun safe(text:String)=text.replace(Regex("[\r\n\"|]")," ").trim()
    private fun csv(v:String):String= if(v.contains(',')) "\"${safe(v)}\"" else safe(v)
    private fun xml(s:String):String=s.replace("&","&amp;").replace("<","&lt;").replace(">","&gt;").replace("\"","&quot;").replace("'","&apos;")
    private fun iso(t:Long)=Instant.ofEpochMilli(t).toString()
    private fun date(t:Long)=Instant.ofEpochMilli(t).atZone(ZoneId.systemDefault()).format(DateTimeFormatter.ofPattern("MM/dd/yyyy"))
    private fun time(t:Long)=Instant.ofEpochMilli(t).atZone(ZoneId.systemDefault()).format(DateTimeFormatter.ofPattern("HH:mm"))
    private fun day(t:Long)=Instant.ofEpochMilli(t).atZone(ZoneId.systemDefault()).toLocalDate()

    fun distanceMiles(fixes:List<TrackFix>):Double{
        var meters=0.0
        for(i in 1 until fixes.size){
            val a=fixes[i-1];val b=fixes[i]
            if(b.epoch-a.epoch > 180_000) continue  // GPS gap: never invent a direct segment.
            val d=haversine(a.lat,a.lon,b.lat,b.lon)
            if(d in 8.0..250.0 && a.accuracy<=50 && b.accuracy<=50)meters+=d
        }
        return meters / 1609.344
    }
    fun haversine(la1:Double,lo1:Double,la2:Double,lo2:Double):Double{
        val d1=Math.toRadians(la2-la1);val d2=Math.toRadians(lo2-lo1)
        val a=sin(d1/2).pow(2)+cos(Math.toRadians(la1))*cos(Math.toRadians(la2))*sin(d2/2).pow(2)
        return 2*6371000*asin(sqrt(a.coerceIn(0.0,1.0)))
    }
    data class Position(val latitude:Double,val longitude:Double,val accuracy:Float?,val interpolated:Boolean)
    fun position(event:Sighting, fixes:List<TrackFix>):Position?{
        if(event.latitude!=null && event.longitude!=null)return Position(event.latitude,event.longitude,event.accuracy,false)
        val before=fixes.lastOrNull{it.epoch<=event.epoch}
        val after=fixes.firstOrNull{it.epoch>=event.epoch}
        if(before==null||after==null)return null
        if(after.epoch-before.epoch>120_000 || before.accuracy>70 || after.accuracy>70)return null
        val ratio=if(after.epoch==before.epoch)0.0 else (event.epoch-before.epoch).toDouble()/(after.epoch-before.epoch)
        return Position(before.lat+(after.lat-before.lat)*ratio,before.lon+(after.lon-before.lon)*ratio,max(before.accuracy,after.accuracy),true)
    }
    fun exportEbird(o:Outing,events:List<Sighting>,fixes:List<TrackFix>):String{
        require(o.country.matches(Regex("[A-Z]{2}"))) { "Set a two-letter eBird country code before export (for example US)." }
        require(o.region.matches(Regex("[A-Za-z0-9-]{1,3}"))) { "Set a 1–3 character state/province code before export (for example MA)." }
        require(o.title.isNotBlank()){"A checklist location name is required."}
        val end=o.ended?:System.currentTimeMillis()
        require(day(o.started)==day(end)){"This outing spans dates. Split into one checklist per calendar date."}
        val totals=events.groupBy{it.code}.mapValues{it.value.sumOf{e->e.delta}}.filterValues{it>0}
        require(totals.isNotEmpty()){ "Record at least one bird before exporting." }
        val protocol=o.protocol
        require(protocol in setOf("Traveling","Stationary","Incidental","Historical")){"Invalid eBird protocol"}
        val duration=max(1,(end-o.started)/60_000).toInt()
        val distance=distanceMiles(fixes)
        require(protocol!="Traveling" || (fixes.size>=2 && distance>0.0)){"Traveling requires a measurable GPS track/distance. Collect a usable track or choose an accurate alternative protocol."}
        val rows=mutableListOf<String>()
        for((code,total) in totals){
            val bird=events.last{it.code==code}
            val parts=bird.scientific.split(' ')
            // Current official eBird Record Format: exactly 19 columns, no header row.
            // Cornell Help Center / Upload Spreadsheet Data to eBird.
            val cols=listOf(bird.common,parts.getOrElse(0){""},parts.getOrElse(1){""},total.toString(),"",
                o.title,o.latitude?.toString()?:"",o.longitude?.toString()?:"",
                date(o.started),time(o.started),o.region,o.country,protocol,o.observers.toString(),
                (if(protocol=="Incidental"||protocol=="Historical")"" else duration.toString()),
                if(o.complete)"Y" else "N",
                if(protocol=="Traveling")"%.3f".format(java.util.Locale.US,distance) else "",
                "","Generated by BirdLog; full track and event times in companion KML")
            rows+=cols.joinToString(",",transform=::csv)
        }
        val result=rows.joinToString("\r\n",postfix="\r\n")
        require(result.toByteArray().size<=1_000_000){"eBird import CSV exceeds the 1 MB limit"}
        return result
    }
    /** Replay changes, subtracting corrections from the newest still-active observation first.
     *  Deleted or reduced observations no longer appear as active blue sighting points.
     *  Raw events, including edits, remain available in the JSON audit trail.
     */
    fun activeSightings(events:List<Sighting>):List<Sighting>{
        val active=mutableListOf<Sighting>()
        for(e in events){
            if(e.delta>0)active+=e
            else if(e.delta<0){
                var remove=-e.delta
                for(i in active.indices.reversed()){
                    if(active[i].code!=e.code || remove<=0)continue
                    val prev=active[i]
                    val trimmed=minOf(remove,prev.delta)
                    val remaining=prev.delta-trimmed
                    remove-=trimmed
                    if(remaining==0)active.removeAt(i) else active[i]=prev.copy(delta=remaining)
                }
            }
        }
        return active
    }
    fun exportKml(o:Outing,events:List<Sighting>,fixes:List<TrackFix>):String{
        val sb=StringBuilder("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<kml xmlns=\"http://www.opengis.net/kml/2.2\" xmlns:gx=\"http://www.google.com/kml/ext/2.2\"><Document>\n")
        sb.append("<name>").append(xml(o.title)).append("</name>\n")
        sb.append("<Style id=\"sighting\"><IconStyle><color>ffff6e00</color><scale>0.75</scale><Icon><href>http://maps.google.com/mapfiles/kml/paddle/blu-circle.png</href></Icon></IconStyle></Style>\n")
        // gx:Track preserves timestamp for every GPS fix. Coordinates are longitude latitude altitude.
        sb.append("<Placemark><name>Travel track</name><gx:Track>\n")
        for(f in fixes)sb.append("<when>").append(iso(f.epoch)).append("</when>\n")
        for(f in fixes)sb.append("<gx:coord>").append(f.lon).append(' ').append(f.lat).append(" 0</gx:coord>\n")
        sb.append("</gx:Track></Placemark>\n")
        activeSightings(events).forEach{e->
            val pos=position(e,fixes)?:return@forEach
            sb.append("<Placemark><name>").append(xml("${e.common} +${e.delta}"))
                .append("</name><styleUrl>#sighting</styleUrl><TimeStamp><when>").append(iso(e.epoch)).append("</when></TimeStamp>")
                .append("<description>").append(xml("${e.scientific}; ${time(e.epoch)}; accuracy=${pos.accuracy ?: "unknown"}m; ${if(pos.interpolated)"INTERPOLATED - not measured" else "recorded near observer"}; event ID=${e.id}"))
                .append("</description><ExtendedData><Data name=\"count_delta\"><value>").append(e.delta)
                .append("</value></Data><Data name=\"interpolated\"><value>").append(pos.interpolated)
                .append("</value></Data></ExtendedData><Point><coordinates>").append(pos.longitude).append(',').append(pos.latitude)
                .append(",0</coordinates></Point></Placemark>\n")
        }
        // Aggregate final totals are kept distinct from per-event GPS placemarks.
        val totals=events.groupBy{it.common}.mapValues{it.value.sumOf{e->e.delta}}.filterValues{it>0}
        sb.append("<Folder><name>Final species totals</name><description>")
        sb.append(xml(totals.entries.joinToString("; "){"${it.key}: ${it.value}"}))
        sb.append("</description></Folder></Document></kml>")
        return sb.toString()
    }
}
